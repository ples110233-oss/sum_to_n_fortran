!=======================================================================
! 程式名稱：sum_to_n
! 功能    ：讀入一個正整數 N，計算 1 + 2 + ... + N 並輸出結果
! 規範    ：Fortran 2008（自由格式，.f90 副檔名）
! 註解說明：Fortran 中「!」之後到行尾都是註解，編譯器會忽略
!=======================================================================

! 宣告主程式開始，sum_to_n 是程式名稱（不能和變數同名）
program sum_to_n

    ! 引入標準內建模組 iso_fortran_env：
    !   intrinsic  → 指定用編譯器內建的模組，而非同名的自訂模組
    !   only:      → 只取出需要的兩個名稱，避免污染命名空間
    !   int64      → 代表「64 位元整數」的種類參數（kind）
    !   error_unit → 標準錯誤輸出（stderr）的裝置編號
    use, intrinsic :: iso_fortran_env, only: int64, error_unit

    ! 關閉隱式型別：所有變數都必須明確宣告
    ! （否則 i~n 開頭會自動當整數、其他當實數，打錯字也不會報錯）
    implicit none

    ! ---------------- 變數宣告區 ----------------
    ! 宣告必須放在所有執行敘述之前
    ! 「::」左邊是型別與屬性，右邊是變數名稱

    ! n：使用者輸入的上限，用 64 位元整數避免太快溢位
    integer(int64) :: n

    ! i：DO 迴圈的計數器，型別要和 n 一致
    integer(int64) :: i

    ! total：用迴圈逐項累加出來的總和
    integer(int64) :: total

    ! formula：用高斯公式 N(N+1)/2 直接算出的總和，用來驗算
    integer(int64) :: formula

    ! ios：讀取狀態碼；0 = 成功，非 0 = 失敗（例如輸入了文字）
    ! 這只是狀態碼，用預設的整數型別即可
    integer :: ios

    ! ---------------- 1. 讀取輸入 ----------------

    ! 印出提示文字：
    !   *              → 輸出到標準輸出（螢幕）
    !   '(a)'          → 格式：a 表示輸出一個字串
    !   advance='no'   → 印完不換行，讓游標停在提示文字後面
    write(*, '(a)', advance='no') '請輸入一個正整數 N: '

    ! 從鍵盤讀入 n：
    !   第一個 *   → 從標準輸入（鍵盤）讀取
    !   第二個 *   → 串列導向格式，依變數型別自動解讀
    !   iostat=ios → 把讀取結果狀態存進 ios，失敗時不會直接當掉
    read(*, *, iostat=ios) n

    ! 檢查讀取是否成功（/= 是「不等於」）
    if (ios /= 0) then
        ! 讀取失敗：把錯誤訊息寫到標準錯誤輸出
        write(error_unit, '(a)') '錯誤：輸入的不是有效的整數。'
        ! 結束程式，並回傳狀態碼 1 給作業系統表示失敗
        stop 1
    ! 結束這個 if 區塊
    end if

    ! 檢查 n 是否為正整數（題目要求從 1 加起）
    if (n < 1) then
        ! 不合法的輸入：輸出錯誤訊息到標準錯誤輸出
        write(error_unit, '(a)') '錯誤：N 必須是正整數（N >= 1）。'
        ! 以狀態碼 1 結束程式
        stop 1
    ! 結束這個 if 區塊
    end if

    ! ---------------- 2. 用迴圈累加 ----------------

    ! 總和先歸零；0_int64 表示「64 位元的整數 0」，型別與 total 一致
    total = 0_int64

    ! DO 迴圈：i 從 1 開始，每次加 1，直到 i = n（包含 n）
    do i = 1_int64, n
        ! 把目前的 i 加進總和：total ← total + i
        total = total + i
    ! 迴圈結束標記，程式會跳回 do 那行繼續下一圈
    end do

    ! ---------------- 3. 用高斯公式驗算 ----------------

    ! 1 + 2 + ... + N = N(N+1)/2
    ! 所有常數都加上 _int64，確保整個運算都用 64 位元進行
    ! n*(n+1) 必為偶數，所以整數除以 2 不會有捨去誤差
    formula = n * (n + 1_int64) / 2_int64

    ! ---------------- 4. 輸出結果 ----------------

    ! 輸出迴圈的結果：
    !   格式 (a, i0, a, i0) 依序對應「字串、整數、字串、整數」
    !   i0 → 整數用剛好需要的最小寬度輸出，不會有多餘空白
    write(*, '(a, i0, a, i0)') '1 加到 ', n, ' 的總和 = ', total

    ! 輸出公式的驗算結果，格式為「字串、整數」
    write(*, '(a, i0)') '公式 N(N+1)/2 驗算   = ', formula

! 主程式結束；後面接的名稱必須和 program 那行相同
end program sum_to_n
